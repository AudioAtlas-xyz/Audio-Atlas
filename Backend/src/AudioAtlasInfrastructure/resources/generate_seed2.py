# ─── Post-processing: build flat relationship lists ────────────────────────────

# Collect all new genre IDs for validation
ALL_NEW_IDS = {g["id"] for g in GENRES}
ALL_REF_IDS = set(EXISTING_GENRE_REFS.keys())

def _resolve(gid):
    if gid in ALL_NEW_IDS or gid in ALL_REF_IDS:
        return True
    print(f"WARNING: unresolvable genre ref '{gid}'", file=sys.stderr)
    return False

genre_records = []
genre_country = []
genre_hierarchy = []
genre_similarity_pairs = set()
genre_similarity = []
genre_instrument = []
genre_sources = []
genre_aliases = []

for g in GENRES:
    genre_records.append({
        "id": g["id"],
        "name": g["name"],
        "startDate": g["startDate"],
        "description": g["description"],
        "isSensitive": False,
        "sensitiveDescription": None,
        "playlistLink": None,
        "authorId": "system",
        "summary": g["summary"],
    })
    for c in g.get("countries", []):
        genre_country.append({"genreId": g["id"], "countryId": c})
    for p in g.get("parents", []):
        if _resolve(p):
            genre_hierarchy.append({"genreId": p, "subgenreId": g["id"]})
    for s in g.get("similar", []):
        if _resolve(s):
            pair = tuple(sorted([g["id"], s]))
            if pair not in genre_similarity_pairs:
                genre_similarity_pairs.add(pair)
                genre_similarity.append({"similarId1": pair[0], "similarId2": pair[1]})
    for inst in g.get("instruments", []):
        genre_instrument.append({"genreId": g["id"], "instrumentId": inst})
    for src in g.get("sources", []):
        genre_sources.append({"genreId": g["id"], "sourceLink": src})
    for alias in g.get("aliases", []):
        genre_aliases.append({"genreId": g["id"], "alias": alias})

output = {
    "existingGenreRefs": EXISTING_GENRE_REFS,
    "existingInstrumentRefs": EXISTING_INSTRUMENT_REFS,
    "genres": genre_records,
    "genreCountry": genre_country,
    "genreHierarchy": genre_hierarchy,
    "genreSimilarity": genre_similarity,
    "genreInstrument": genre_instrument,
    "genreSources": genre_sources,
    "genreAliases": genre_aliases,
}

out_path = os.path.join(os.path.dirname(__file__), "genreSeeding2.json")
with open(out_path, "w", encoding="utf-8") as f:
    json.dump(output, f, indent=2, ensure_ascii=False)

